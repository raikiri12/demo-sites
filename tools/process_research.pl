for my $slug (sort keys %updates) {
  my $path = "$dir/$slug.json";

  open my $in, '<:encoding(UTF-8)', $path or die "Cannot read $path: $!";
  local $/;
  my $text = <$in>;
  close $in;

  my $json = JSON::PP->new->utf8(0);
  my $data = $json->decode($text);

  my $u = $updates{$slug} or die "No update for $slug";
  $data->{review_points} = $u->{review_points};
  $data->{complaints} = $u->{complaints};
  delete $data->{reviews_raw};

  my @missing;
  for my $f (qw/email services prices payment amenities review_points complaints review_summary/) {
    my $v = $data->{$f};
    if (!defined $v || $v eq '' || (ref $v eq 'ARRAY' && @$v == 0)) {
      push @missing, $f;
    }
  }
  push @missing, 'photos' if exists $data->{photos_count} && $data->{photos_count} == 0;
  $data->{missing} = [ sort @missing ];

  # Preserve original key order across all objects.
  my @keys = ($text =~ /"([^"\\]+)"\s*:/g);
  my %seen;
  my @order;
  for my $k (@keys) {
    push @order, $k unless $seen{$k}++;
  }
  my %order = map { $order[$_] => $_ } 0..$#order;

  my $out_json = JSON::PP->new->utf8(0)->pretty(1)->indent_length(1)->space_after(1)->canonical(0)->sort_by(sub {
    my $oa = $order{$JSON::PP::a} // 9999;
    my $ob = $order{$JSON::PP::b} // 9999;
    ($oa <=> $ob) || ($JSON::PP::a cmp $JSON::PP::b);
  });

  open my $out, '>:encoding(UTF-8)', $path or die "Cannot write $path: $!";
  print $out $out_json->encode($data);
  close $out;

  print "$slug: points=" . scalar(@{$u->{review_points}}) . " complaints=" . (@{$u->{complaints}} ? 'да' : 'нет') . "\n";
}
