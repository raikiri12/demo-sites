CHECK = ["amenities", "complaints", "email", "payment", "prices", "services", "review_summary"]

for slug, patch in DATA.items():
    p = f"data/research/{slug}.json"
    d = json.load(open(p, encoding="utf-8"))
    d["review_points"] = patch["review_points"]
    d["complaints"] = patch["complaints"]
    d.pop("reviews_raw", None)
    missing = []
    for k in CHECK:
        if k == "review_summary":
            if not d.get("review_points"):
                missing.append(k)
        else:
            if not d.get(k):
                missing.append(k)
    if not d.get("photos_count"):
        missing.append("photos")
    d["missing"] = sorted(missing)
    json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{slug}: points={len(patch['review_points'])} complaints={len(patch['complaints'])} missing={d['missing']}")
